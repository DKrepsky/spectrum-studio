import type { SessionState } from '../bindings/SessionState';
import { formatFrequencyShort } from '../format/frequency';
import { useSession } from '../state/session';
import { sameConfig } from '../state/sourceConfig';
import { useFrameTick } from '../state/useFrameTick';
import { FrequencyInput } from './FrequencyInput';
import { SourceSelector } from './SourceSelector';
import type { Selection } from './sources/SourceManager';

const STATE_LABEL: Record<SessionState, string> = {
  disconnected: 'Disconnected',
  connecting: 'Connecting…',
  connected: 'Connected',
  acquiring: 'Acquiring',
  disconnecting: 'Disconnecting…',
};

interface Props {
  onOpenSources: (initial?: Selection) => void;
  onExport: () => void;
}

export function Toolbar({ onOpenSources, onExport }: Props) {
  const status = useSession((s) => s.status);
  const selected = useSession((s) => s.selectedConfig);
  const busy = useSession((s) => s.busy);
  const hasFrame = useFrameTick(1000) !== null;
  const { connect, disconnect, run, stop, applySettings } = useSession.getState();

  const state = status?.state ?? 'disconnected';
  const source = status?.source ?? null;
  const connected = state === 'connected' || state === 'acquiring';
  const transitioning = state === 'connecting' || state === 'disconnecting' || busy !== null;
  const caps = source?.capabilities;
  const switchPending = connected && source !== null && !sameConfig(source.config, selected);

  return (
    <header className="toolbar" role="toolbar" aria-label="Main toolbar">
      <div className="brand">
        <span className="brand-mark" aria-hidden>
          ▲
        </span>
        Spectrum Studio
      </div>

      <div className="toolbar-group">
        <SourceSelector onOpenSources={onOpenSources} />
        {switchPending && (
          <button
            onClick={() => void connect()}
            disabled={transitioning}
            title="Stop the current source and connect the selected one"
            data-testid="switch-button"
          >
            Switch
          </button>
        )}
        {connected ? (
          <button
            onClick={() => void disconnect()}
            disabled={transitioning}
            data-testid="disconnect-button"
          >
            Disconnect
          </button>
        ) : (
          <button
            onClick={() => void connect()}
            disabled={transitioning}
            data-testid="connect-button"
          >
            Connect
          </button>
        )}
        {state === 'acquiring' ? (
          <button
            className="primary stop"
            onClick={() => void stop()}
            disabled={transitioning}
            data-testid="stop-button"
          >
            ■ Stop
          </button>
        ) : (
          <button
            className="primary"
            onClick={() => void run()}
            disabled={transitioning}
            data-testid="run-button"
          >
            ▶ Run
          </button>
        )}
        <span className={`state-pill state-${state}`} data-testid="session-state" role="status">
          {STATE_LABEL[state]}
        </span>
        {source?.simulated && (
          <span
            className="badge simulated"
            title="Data is generated by the built-in simulator"
            data-testid="simulated-badge"
          >
            SIMULATED
          </span>
        )}
      </div>

      <div className="toolbar-group">
        <label className="field">
          <span>Center</span>
          <FrequencyInput
            label="Center frequency"
            value={source?.settings.centerHz ?? 0}
            min={caps?.tuning?.minHz}
            max={caps?.tuning?.maxHz}
            step={source ? source.settings.spanHz / 10 : 1000}
            disabled={!caps?.tuning || busy === 'applying'}
            title={caps && !caps.tuning ? 'This source cannot be tuned' : undefined}
            onCommit={(centerHz) => void applySettings({ centerHz, spanHz: null, params: {} })}
          />
        </label>
        <label className="field">
          <span>Span</span>
          <select
            aria-label="Span"
            value={source?.settings.spanHz ?? ''}
            disabled={!caps || caps.spanOptionsHz.length === 0 || busy === 'applying'}
            title={
              caps && caps.spanOptionsHz.length === 0 ? 'This source has a fixed span' : undefined
            }
            onChange={(e) =>
              void applySettings({ centerHz: null, spanHz: Number(e.target.value), params: {} })
            }
          >
            {source && !caps?.spanOptionsHz.includes(source.settings.spanHz) && (
              <option value={source.settings.spanHz}>
                {formatFrequencyShort(source.settings.spanHz)}
              </option>
            )}
            {!source && <option value="">—</option>}
            {caps?.spanOptionsHz.map((hz) => (
              <option key={hz} value={hz}>
                {formatFrequencyShort(hz)}
              </option>
            ))}
          </select>
        </label>
      </div>

      <div className="toolbar-group toolbar-end">
        <button
          onClick={onExport}
          disabled={!hasFrame}
          data-testid="export-button"
          title={hasFrame ? 'Export the displayed spectrum to CSV' : 'No spectrum to export yet'}
        >
          Export CSV
        </button>
      </div>
    </header>
  );
}
